let done = false;

export async function seedContent() {
  if (done) return;
  done = true;
  const titles = CONTENT_SEEDS.map((c) => c.title);
  const existing = await db.select({ title: resources.title }).from(resources).where(inArray(resources.title, titles));
  const have = new Set(existing.map((e) => e.title));
  const missing = CONTENT_SEEDS.filter((c) => !have.has(c.title));
  if (!missing.length) return;
  const [admin] = await db.select({ id: users.id }).from(users).where(eq(users.role, "admin")).limit(1);
  if (!admin) return;
  const now = Date.now();
  await db.insert(resources).values(
    missing.map((c, i) => {
      const createdAt = new Date(now - (missing.length - i) * 3 * 60 * 60 * 1000);
      return {
        section: c.section,
        title: c.title,
        summary: c.summary,
        content: c.content,
        level: c.level,
        subject: c.subject,
        gradeGroup: c.gradeGroup,
        tags: c.tags,
        aiTool: c.aiTool ?? null,
        featured: c.featured ?? false,
        status: "approved" as const,
        authorId: admin.id,
        createdAt,
        updatedAt: createdAt,
      };
    }),
  );
}
